function painCode(c) {
  const m = /·\s*([A-F]\d|[a-z0-9_]{8,})\s*(?:·|$)/.exec(String(c.topic || ''));
  if (m && PAINS[m[1]]) return m[1];
  if (m && SLUGS[m[1]]) return SLUGS[m[1]];
  const text = `${c.hook || ''}\n${c.text || ''}`;
  for (const [re, code] of KEYWORDS) if (re.test(text)) return code;
  return null;
}

/** Додає до креативу поле `pain` ({code,title,persona} або null). */
function withPain(c) {
  const code = painCode(c);
  return { ...c, pain: code ? { code, title: PAINS[code].title, persona: PAINS[code].persona } : null };
}

