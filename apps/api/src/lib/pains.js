// Для креативів без коду в темі: перший збіг виграє.
const KEYWORDS = [
  [/відпустк|ключов\w+ людин|на одній людин/i, 'C1'],
  [/акт для клієнт/i, 'A2'],
  [/заяв\w+ (?:на день|губл)|telegram-чат|між чатами/i, 'B1'],
  [/не прижив|ніхто не користу|не користу\w+ся|нічого не змін|оплатили chatgpt|купили бота/i, 'D3'],
  [/з чого почат|усі вже впроваджують|ви ще вручну/i, 'D1'],
  [/менеджер\w* (?:витрачає|може|виконувати)|трьох менеджер|рутин/i, 'A1'],
];

function painCode(c) {
  const m = /·\s*([A-D]\d)\b/.exec(String(c.topic || ''));
  if (m && PAINS[m[1]]) return m[1];
  const text = `${c.hook || ''}\n${c.text || ''}`;
  for (const [re, code] of KEYWORDS) if (re.test(text)) return code;
  return null;
}

/** Додає до креативу поле `pain` ({code,title,persona} або null). */
function withPain(c) {
  const code = painCode(c);
  return { ...c, pain: code ? { code, title: PAINS[code].title, persona: PAINS[code].persona } : null };
}

module.exports = { PAINS, painCode, withPain };
